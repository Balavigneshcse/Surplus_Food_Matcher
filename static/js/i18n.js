const STORAGE_KEY = 'annamsetu.lang';

export function getLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === 'ta' ? 'ta' : 'en';
  } catch {
    return 'en';
  }
}

export function setLang(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // private window or blocked storage: the choice just isn't remembered
  }
  document.documentElement.lang = lang;
  applyI18n();
}

export function toggleLang() {
  setLang(getLang() === 'en' ? 'ta' : 'en');
}

// The label for `key` in the current language (falls back to English, then to the key).
export function t(key) {
  return label(key, getLang());
}

// The label for `key` in a given language: the printed cook card shows English and Tamil together.
export function label(key, lang) {
  return LABELS[lang]?.[key] ?? LABELS.en[key] ?? key;
}

export function applyI18n(root = document) {
  document.documentElement.lang = getLang();
  for (const node of root.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
  }
}
